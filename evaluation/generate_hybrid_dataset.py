"""
SecureEV — Hybrid Dataset Generator

Combines three sources into one CSV:
  1. SecureEV authenticated normal traffic (BMS, Motor, OBC)
     — valid HMAC, generated by the real ECU modules
  2. SecureEV attacker traffic (all five injectable attack types)
     — invalid or replayed, generated by the Attacker module
  3. KAIST real-vehicle traffic, both normal and attack frames
     — no HMAC, since KAIST predates authentication standards

Output: dataset/hybrid/secureev_hybrid_dataset.csv
"""

import sys, os, csv, random
sys.path.insert(0, os.path.dirname(
    os.path.dirname(os.path.abspath(__file__))
))

from bus.virtual_bus import VirtualBus
from modules.kms import KMS
from modules.bms_ecu import BMSECU
from modules.motor_ecu import MotorECU
from modules.obc_ecu import OBCECU
from attacker.attacker import Attacker

MASTER_KEY = b'secureev_master_key_32bytes!!!!!'

# Keep a single epoch throughout generation so the evaluation
# script can verify every SecureEV frame with a fresh KMS at
# epoch 0 without needing to track rotation history per row.
ROTATION_INTERVAL = 10_000_000

N_NORMAL_PER_ECU  = 2000
N_ATTACK_PER_TYPE = 500

KAIST_DIR = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    '..', 'dataset', 'kaist'
)
KAIST_FILES = [
    ("DoS_dataset.csv",   "KAIST_DoS"),
    ("Fuzzy_dataset.csv", "KAIST_Fuzzy"),
    ("RPM_dataset.csv",   "KAIST_RPM"),
    ("gear_dataset.csv",  "KAIST_Gear"),
]
SAMPLE_NORMAL_PER_FILE = 1500
SAMPLE_ATTACK_PER_FILE = 1500

# CAN IDs reserved by SecureEV — excluded from KAIST sampling
# so a coincidental overlap never contaminates the whitelist
RESERVED_IDS = {0x100, 0x200, 0x300, 0x600}

rows = []


def add_row(origin, label, dataset, frame, detail=""):
    rows.append({
        "origin":      origin,
        "label":       label,
        "dataset":     dataset,
        "can_id":      hex(frame.can_id),
        "counter":     frame.counter,
        "payload_hex": frame.payload.hex(),
        "mac_hex":     frame.mac.hex(),
        "detail":      detail,
    })


def generate_secureev_traffic():
    bus = VirtualBus()
    kms = KMS(MASTER_KEY, rotation_interval=ROTATION_INTERVAL)
    bms   = BMSECU(kms, bus)
    motor = MotorECU(kms, bus)
    obc   = OBCECU(kms, bus, charger_allowlist=[0x01, 0x02])
    atk   = Attacker(bus)

    print("Generating SecureEV normal traffic...")
    captured_bms_frame = None
    for i in range(N_NORMAL_PER_ECU):
        v = round(390 + random.uniform(0, 20), 1)
        t = round(20  + random.uniform(0, 30), 1)
        s = random.randint(60, 100)
        f = bms.transmit(v, t, s)
        add_row("secureev", "normal", "BMS", f,
                f"V={v} T={t} SOC={s}")
        captured_bms_frame = f

    for i in range(N_NORMAL_PER_ECU):
        torque = round(100 + random.uniform(0, 100), 1)
        speed  = random.randint(500, 2500)
        f = motor.transmit(torque, speed, 3)
        add_row("secureev", "normal", "Motor", f,
                f"torque={torque} speed={speed}")

    for i in range(N_NORMAL_PER_ECU):
        current = random.randint(8000, 20000)
        f = obc.transmit(current, 0x01, 0x01)
        if f is not None:
            add_row("secureev", "normal", "OBC", f,
                    f"current={current}mA charger=0x01")

    print("Generating SecureEV attacker traffic...")
    for i in range(N_ATTACK_PER_TYPE):
        f = atk.bms_spoof(999.9, 200.0, 0)
        add_row("secureev", "attack", "BMS_Spoof", f,
                "voltage=999.9 temp=200 — emergency stop trigger attempt")

    for i in range(N_ATTACK_PER_TYPE):
        f = atk.drive_by_wire_inject(500.0, 3000, 3)
        add_row("secureev", "attack", "Drive_By_Wire", f,
                "torque=500 speed=3000 — steering/braking takeover attempt")

    for i in range(N_ATTACK_PER_TYPE):
        f = atk.rogue_charging(0xAA, 32000)
        add_row("secureev", "attack", "Rogue_Charging", f,
                "charger_id=0xAA — unknown charging station")

    for i in range(N_ATTACK_PER_TYPE):
        f = atk.replay(captured_bms_frame)
        add_row("secureev", "attack", "Replay", f,
                f"counter={captured_bms_frame.counter} — replayed valid frame")

    n_before = len(bus.frames)
    atk.can_flood(0x100, N_ATTACK_PER_TYPE)
    for f in bus.frames[n_before:]:
        add_row("secureev", "attack", "CAN_Flood", f,
                "flood injection targeting 0x100")


def generate_kaist_sample():
    for filename, name in KAIST_FILES:
        filepath = os.path.join(KAIST_DIR, filename)
        if not os.path.exists(filepath):
            print(f"[SKIP] {filename} not found")
            continue

        print(f"Sampling {name}...")
        ctr = {}
        normal_taken = 0
        attack_taken = 0

        with open(filepath, 'r') as f:
            for row in csv.reader(f):
                if len(row) < 5:
                    continue
                try:
                    can_id = int(row[1], 16)
                    if can_id in RESERVED_IDS:
                        continue
                    dlc = int(row[2])
                    payload = bytes(
                        [int(row[3+i], 16)
                         for i in range(min(dlc, 4))]
                    ).ljust(4, b'\x00')
                    flag = row[-1].strip()
                except (ValueError, IndexError):
                    continue

                ctr[can_id] = (ctr.get(can_id, -1) + 1) % 65536
                from models.frames import CANFrame
                frame = CANFrame(
                    can_id=can_id,
                    counter=ctr[can_id],
                    payload=payload,
                    mac=b'\x00\x00',
                    timestamp=float(row[0])
                )

                if flag == 'R' and normal_taken < SAMPLE_NORMAL_PER_FILE:
                    add_row("kaist", "normal", name, frame,
                            "real vehicle traffic, no HMAC")
                    normal_taken += 1
                elif flag == 'T' and attack_taken < SAMPLE_ATTACK_PER_FILE:
                    add_row("kaist", "attack", name, frame,
                            "injected attack, no HMAC")
                    attack_taken += 1

                if normal_taken >= SAMPLE_NORMAL_PER_FILE and \
                        attack_taken >= SAMPLE_ATTACK_PER_FILE:
                    break

        print(f"  {name}: {normal_taken} normal, "
              f"{attack_taken} attack frames sampled")


def write_dataset():
    out_path = os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        '..', 'dataset', 'hybrid', 'secureev_hybrid_dataset.csv'
    )
    fieldnames = ["origin", "label", "dataset", "can_id",
                  "counter", "payload_hex", "mac_hex", "detail"]

    with open(out_path, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"\nWritten {len(rows)} rows to {out_path}")


def print_summary():
    from collections import Counter
    counts = Counter((r["origin"], r["label"], r["dataset"])
                     for r in rows)
    print("\n--- Hybrid Dataset Summary ---")
    for key in sorted(counts):
        origin, label, dataset = key
        print(f"  {origin:<10} {label:<8} {dataset:<16} "
              f": {counts[key]:,}")
    print(f"  {'TOTAL':<10} {'':<8} {'':<16} : {len(rows):,}")


if __name__ == "__main__":
    print("SecureEV — Hybrid Dataset Generator\n")
    generate_secureev_traffic()
    generate_kaist_sample()
    write_dataset()
    print_summary()